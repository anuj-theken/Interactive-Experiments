#!/usr/bin/env python3
"""Package this site the way the 2026 build is deployed on the-ken.com.

  python3 wp/build.py

Writes:
  wp/dist/gifting-2026/          → copy to the theme's assets/assets_3_0/gifting-2026/
      gifting-2026.css, js/ (app.js, gift-tag.js, tag-theme.js, gifting/*), data/gifting-2026.json, assets/, VERSION
  wp/gifting-2026-views.php      → copy to template-parts/template-3-0/gifting-2026-views.php
wp/page-gifting-2026-3-0.php is the page template itself (hand-written; copy to the theme root).
"""
import re, shutil, time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'wp' / 'dist' / 'gifting-2026'

html = (ROOT / 'index.html').read_text()
views = re.search(r'<!-- views:start -->(.*)<!-- views:end -->', html, re.S).group(1)
views = views.replace('src="assets/', 'src="<?php echo esc_url( $gk26_url ); ?>/assets/')
(ROOT / 'wp' / 'gifting-2026-views.php').write_text(
    "<?php // Generated by wp/build.py from index.html (between the views markers). Do not edit; re-run the build. ?>\n" + views.strip() + "\n")

if OUT.exists():
    shutil.rmtree(OUT)
(OUT / 'js').mkdir(parents=True)
shutil.copy(ROOT / 'styles.css', OUT / 'gifting-2026.css')
for f in ('app.js', 'gift-tag.js', 'tag-theme.js'):
    shutil.copy(ROOT / 'scripts' / f, OUT / 'js' / f)
shutil.copytree(ROOT / 'scripts' / 'gifting', OUT / 'js' / 'gifting')
shutil.copytree(ROOT / 'scripts' / 'vendor', OUT / 'js' / 'vendor')  # Matter.js for the footer pile
(OUT / 'data').mkdir()
shutil.copy(ROOT / 'data' / 'gifting-2026.json', OUT / 'data' / 'gifting-2026.json')
(OUT / 'assets').mkdir()
shutil.copytree(ROOT / 'assets' / 'fonts', OUT / 'assets' / 'fonts')
shutil.copy(ROOT / 'assets' / 'logo.png', OUT / 'assets' / 'logo.png')
(OUT / 'VERSION').write_text(time.strftime('%Y%m%d%H%M') + '\n')
print('Built', OUT.relative_to(ROOT), 'and wp/gifting-2026-views.php')
