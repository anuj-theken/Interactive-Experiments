# Bundles every parts/<slot>--<variant>.svg into parts.js so pages can use them
# (including when opened straight from disk). Run after adding or replacing parts:
#   python3 build.py
import json, os, re
here = os.path.dirname(os.path.abspath(__file__))
parts = {}
for f in sorted(os.listdir(os.path.join(here, 'parts'))):
    if not f.endswith('.svg') or '--' not in f:
        continue
    src = open(os.path.join(here, 'parts', f), encoding='utf-8').read()
    m = re.search(r'<svg[^>]*>(.*)</svg>', src, re.S)
    vb = re.search(r'viewBox="([^"]+)"', src)
    if not m or not vb or vb.group(1).split()[2:] != ['1000', '1000']:
        print('SKIPPED (needs a 1000x1000 viewBox):', f)
        continue
    inner = re.sub(r'<\?xml.*?\?>|<!--.*?-->', '', m.group(1), flags=re.S).strip()
    parts[f[:-4]] = inner
with open(os.path.join(here, 'parts.js'), 'w', encoding='utf-8') as out:
    out.write('// Generated by build.py from parts/*.svg. Do not edit by hand.\nwindow.KIT_PARTS = ' + json.dumps(parts, indent=0) + ';\n')
print(len(parts), 'parts bundled into parts.js')
